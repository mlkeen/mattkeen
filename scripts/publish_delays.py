"""Validate and aggregate FRA delay-by-code into a small web-ready JSON.

Input: data/processed/delay_by_code.csv (generated by scripts/fra_etl.py)
Output: app/data/fra_delays.json

Use delay minutes from delay-by-code; NEVER sum host_train_miles (repeated per code).
Unknown code names are retained as codes, not guessed descriptions.
"""
import argparse
import csv
import json
import math
import os
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / 'data/processed/delay_by_code.csv'
OUTPUT = ROOT / 'app/data/fra_delays.json'


def compile_delays(source):
    aggregates = defaultdict(float)
    period_set = set()
    numeric_rows = 0
    empty_minutes = 0
    zero_minutes = 0
    sources = set()
    negative_examples = []
    with Path(source).open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream)
        required = {'fiscal_year', 'fiscal_quarter', 'service', 'sub_service',
                    'responsibility', 'delay_code', 'delay_minutes', 'host_code',
                    'source_workbook', 'source_sheet', 'source_excel_row'}
        missing = required - set(reader.fieldnames or [])
        if missing:
            raise ValueError('Missing required delay fields: ' + ', '.join(sorted(missing)))
        for lineno, row in enumerate(reader, 2):
            try:
                year = int(row['fiscal_year'])
                quarter = int(row['fiscal_quarter'])
                if not 2000 <= year <= 2100 or quarter not in (1, 2, 3, 4):
                    raise ValueError('bad fiscal period')
                service = row['service'].strip()
                sub = row['sub_service'].strip()
                responsibility = row['responsibility'].strip()
                code = row['delay_code'].strip()
                host = row['host_code'].strip()
                source_name = row['source_workbook'].strip()
                source_sheet = row['source_sheet'].strip()
                excel_row = row['source_excel_row'].strip()
                if not all((service, sub, responsibility, code, host, source_name, source_sheet, excel_row)):
                    raise ValueError('required identity or provenance is empty')
                if row['delay_minutes'].strip() == '':
                    empty_minutes += 1
                    continue
                minutes = float(row['delay_minutes'])
                if not math.isfinite(minutes):
                    raise ValueError('nonfinite delay minutes')
                if minutes < 0:
                    negative_examples.append((lineno, minutes))
                    continue
                if minutes == 0:
                    zero_minutes += 1
            except (ValueError, TypeError) as exc:
                raise ValueError(f'Invalid delay row {lineno}: {exc}') from exc
            period_set.add((year, quarter))
            sources.add(source_name)
            numeric_rows += 1
            aggregates[(year, quarter, service, sub, responsibility, host, code)] += minutes
    if negative_examples:
        examples = ', '.join(f'CSV line {n} ({v})' for n,v in negative_examples[:5])
        raise ValueError(f'{len(negative_examples)} negative delay-minute entries; review source instead of silently discarding: {examples}')
    if not aggregates:
        raise ValueError('No numeric delay observations found')
    records = [{'year': y, 'quarter': q, 'service': svc, 'sub_service': sub,
                'responsibility': responsible, 'host': host, 'code': code,
                'minutes': round(total, 5)}
               for (y, q, svc, sub, responsible, host, code), total in sorted(aggregates.items())]
    return {'version': 1, 'source': 'FRA quarterly Delay Metrics / DelayandMileage',
            'units': 'delay minutes', 'periods': [f'FY{y} Q{q}' for y,q in sorted(period_set)],
            'source_workbooks': sorted(sources), 'rows_processed': numeric_rows,
            'source_rows_blank_minutes': empty_minutes, 'source_rows_zero_minutes': zero_minutes,
            'rows_aggregated': len(records), 'records': records,
            'warning': 'Host train-miles are repeated by delay code and not summed. These figures are delay minutes, not rates or passenger delay.'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=INPUT)
    p.add_argument('--destination', type=Path, default=OUTPUT)
    args = p.parse_args()
    if not args.source.exists():
        p.error(f'Missing {args.source}. Run scripts/fra_etl.py first.')
    result = compile_delays(args.source)
    args.destination.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.destination.with_name(args.destination.name + '.tmp')
    try:
        with tmp.open('w', encoding='utf-8') as handle:
            json.dump(result, handle, ensure_ascii=False, separators=(',', ':'), allow_nan=False)
        os.replace(tmp, args.destination)
    finally:
        tmp.unlink(missing_ok=True)
    print(f"Published {result['rows_aggregated']:,} aggregates from {result['rows_processed']:,} delay observations")
    print(f"Quarters: {len(result['periods'])}; source workbooks: {len(result['source_workbooks'])}")
    print(f"Blank delay minutes: {result['source_rows_blank_minutes']:,}; retained zero-minute entries: {result['source_rows_zero_minutes']:,}")
    print(f'Output: {args.destination}')
    print('Restart Flask for fresh data.')


if __name__ == '__main__':
    main()
